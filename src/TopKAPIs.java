import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/*
## Problem: Top K APIs by Load

You are given two integer arrays of size `n`:

- `apiIndex[i]`: The ID of the API called in the `i`-th event.
- `loads[i]`: The load generated by that API call.

Multiple events may correspond to the same API. The total cumulative load of an API is the sum of the loads across all its occurrences.

Your task is to identify the **top `k` APIs based on their total cumulative load**.

### Selection Rules

1. APIs are ranked by higher total cumulative load.
2. If two APIs have the same total cumulative load, the API with the smaller API index is ranked higher.

Return a list of `k` API indices, sorted in descending order of total cumulative load. Break ties using ascending API index order.

### Function Description

Complete the function `topKAPIs` with the following parameters:

- `int[] apiIndex`: An array containing API IDs for each event.
- `int[] loads`: An array containing the load generated by each event.
- `int k`: The number of top APIs to return.

### Returns

A list of `k` API indices ranked according to the selection rules.

### Example 1

**Input:**
```text
apiIndex = [1, 2, 1, 3, 2]
loads    = [6, 10, 9, 15, 5]
k = 2
```

**Explanation:**

Calculate the total cumulative load for each API:

| API Index | Calculation | Total Load |
|---|---|---:|
| 1 | 6 + 9 | 15 |
| 2 | 10 + 5 | 15 |
| 3 | 15 | 15 |

All three APIs have the same total load of `15`. According to the tie-breaking rule, smaller API indices rank higher.

The sorted API ranking is:

```text
API 1 → Load 15
API 2 → Load 15
API 3 → Load 15
```

**Output:**
```text
[1, 2]
```

### Example 2

**Input:**
```text
apiIndex = [1, 2, 1, 3]
loads    = [6, 10, 9, 15]
k = 2
```

**Explanation:**

The cumulative loads are:

| API Index | Total Load |
|---|---:|
| 1 | 15 |
| 2 | 10 |
| 3 | 15 |

APIs 1 and 3 have the highest load of `15`. API 1 ranks higher because its index is smaller.

**Output:**
```text
[1, 3]
```
.
 */

public class TopKAPIs {

    public static void main(String[] args) {

    }

    public static List<Integer> topKAPIs(int[] apiIndex, int[] loads, int k) {

        Map<Integer, Long> map = new HashMap<>();

        for (int i = 0; i < apiIndex.length; i++) {
            map.put( apiIndex[i],
                    map.getOrDefault(apiIndex[i], 0L) + loads[i]
            );
        }

        List<Integer> list = new ArrayList<>(map.keySet());

        list.sort((a, b) -> {
            if (!map.get(a).equals(map.get(b))) {
                return Long.compare(map.get(b), map.get(a));
            }
            return Integer.compare(a, b);
        });
        return list.subList(0, k);
    }
}
